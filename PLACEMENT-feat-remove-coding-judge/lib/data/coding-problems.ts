function generatedCodingProblem(companyId: CompanyId, index: number): CodingProblem {
  const template = CODING_TEMPLATES[index % CODING_TEMPLATES.length]
  const focus = COMPANY_FOCUS[companyId]
  const round = Math.floor(index / CODING_TEMPLATES.length) + 1
  return cp({
    id: `code-${companyId}-gen-${index + 1}`,
    companyId,
    title: `${focus.label} ${template.title} ${round}`,
    level: companyId === "zoho" && template.level === "medium" ? "machine-round" : template.level,
    difficulty: companyId === "zoho" && template.difficulty === "easy" ? "medium" : template.difficulty,
    topics: [focus.label.toLowerCase().replace(/\s+/g, "-"), ...template.topics],
    prompt: template.prompt,
    inputFormat: template.inputFormat,
    outputFormat: template.outputFormat,
    constraints: template.constraints,
    starterCode: template.starterCode,
    testCases: template.testCases,
    editorial: template.editorial,
    estimatedMinutes: companyId === "zoho" ? template.estimatedMinutes + 6 : template.estimatedMinutes,
    sourceId: focus.sourceId,
  })
}

export const GENERATED_CODING_PROBLEMS: CodingProblem[] = (Object.keys(COMPANY_FOCUS) as CompanyId[]).flatMap((companyId) =>
  Array.from({ length: COMPANY_FOCUS[companyId].count }, (_, index) => generatedCodingProblem(companyId, index)),
)

export const ALL_CODING_PROBLEMS: CodingProblem[] = [...CODING_PROBLEMS, ...GENERATED_CODING_PROBLEMS]

const CODING_PROBLEMS_BY_COMPANY = (Object.keys(COMPANY_FOCUS) as CompanyId[]).reduce(
  (acc, companyId) => {
    acc[companyId] = ALL_CODING_PROBLEMS.filter(
      (problem) => problem.companyId === companyId || problem.companyId === "general",
    )
    return acc
  },
  {} as Record<CompanyId, CodingProblem[]>,
)

export function codingProblemsForCompany(companyId: CompanyId): CodingProblem[] {
  return CODING_PROBLEMS_BY_COMPANY[companyId] ?? []
}
