function cp(problem: Omit<CodingProblem, keyof typeof review>): CodingProblem {
  return {
    ...problem,
    editorial: beginnerEditorial(problem),
    ...review,
  }
}

function beginnerEditorial(problem: Omit<CodingProblem, keyof typeof review>): string {
  const checklist =
    "First understand what the input represents, then solve one sample by hand. Keep the return value exact; extra spaces or missing returns can fail samples. "
  return `${checklist}${problem.editorial}`
}

